#!/usr/bin/env python3
"""
Regenerate CHANGELOG.html from Conventional Commit subjects.

WHY GENERATED
    A hand-maintained changelog drifts the moment someone forgets to update it,
    and a stale changelog is worse than none. The commit history is already the
    authoritative record, and the Conventional Commits convention makes it
    machine-readable — so the changelog is derived, never edited.

USAGE
    python3 tools/generate_changelog.py            # rewrites CHANGELOG.html
    python3 tools/generate_changelog.py --check    # non-zero if out of date
"""

from __future__ import annotations

import argparse
import collections
import html
import os
import re
import subprocess

PROJECT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(PROJECT, "CHANGELOG.html")

#: Conventional Commit type -> section heading, in display order.
TYPES = collections.OrderedDict(
    [
        ("feat", "Features"),
        ("fix", "Fixes"),
        ("perf", "Performance"),
        ("refactor", "Refactoring"),
        ("test", "Tests"),
        ("docs", "Documentation"),
        ("chore", "Tooling"),
        ("style", "Style"),
    ]
)

SUBJECT = re.compile(
    r"^(?P<type>\w+)(?:\((?P<scope>[^)]*)\))?(?P<bang>!)?: (?P<desc>.+)$"
)

HEAD = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>ESX Bank Studio — Changelog</title>
<style>
  :root{--bg:#12100d;--panel:#1b1814;--panel2:#231f19;--line:#3a332a;--amber:#ff9d2e;
    --lcd:#ffb454;--green:#7fd68a;--red:#ff6b5e;--txt:#e8e0d4;--muted:#9d9384;
    --mono:ui-monospace,"SF Mono",Menlo,Consolas,monospace;}
  *{box-sizing:border-box}
  body{margin:0;background:var(--bg);color:var(--txt);
    font:15px/1.65 -apple-system,BlinkMacSystemFont,"Segoe UI",Helvetica,Arial,sans-serif;padding:0 0 80px}
  .wrap{max-width:900px;margin:0 auto;padding:0 24px}
  header{border-bottom:2px solid var(--amber);background:linear-gradient(180deg,#1f1a13,#12100d);padding:40px 0 24px}
  h1{margin:0 0 8px;font-size:28px} h1 span{color:var(--amber)}
  .sub{color:var(--muted)}
  h2{margin:36px 0 8px;font-size:20px;color:var(--lcd);border-left:3px solid var(--amber);padding-left:12px}
  h3{margin:22px 0 6px;font-size:15.5px;border-bottom:1px solid var(--line);padding-bottom:4px}
  code{font-family:var(--mono);font-size:.85em;background:var(--panel2);padding:1px 6px;
    border-radius:3px;color:var(--muted)}
  ul{padding-left:22px} li{margin:6px 0}
  li b{color:var(--lcd)}
  .breaking{color:var(--red);font-weight:600}
  .note{background:var(--panel);border:1px solid var(--line);border-left:4px solid var(--amber);
    border-radius:7px;padding:14px 16px;margin:14px 0;color:var(--muted);font-size:13.5px}
  footer{margin-top:44px;padding-top:16px;border-top:1px solid var(--line);color:var(--muted);font-size:13px}
</style>
</head>
<body>
<header><div class="wrap">
  <h1>ESX Bank Studio — <span>Changelog</span></h1>
  <p class="sub">Generated from Conventional Commit subjects. Do not edit by hand —
     run <code>python3 tools/generate_changelog.py</code>.</p>
</div></header>
<div class="wrap">
<div class="note">Newest first within each section. <span class="breaking">Red</span> marks a
breaking change (a <code>!</code> in the commit subject).</div>
"""

FOOT = """
<footer>Regenerated by <code>tools/generate_changelog.py</code>.</footer>
</div>
</body>
</html>
"""


def commits() -> list[tuple[str, str]]:
    """(short sha, subject) for every commit, newest first."""
    out = subprocess.run(
        ["git", "log", "--pretty=format:%h\x1f%s"],
        capture_output=True,
        text=True,
        cwd=PROJECT,
        check=True,
    ).stdout
    rows = []
    for line in out.splitlines():
        if "\x1f" in line:
            sha, subject = line.split("\x1f", 1)
            rows.append((sha, subject))
    return rows


def render() -> str:
    groups: dict[str, list[str]] = collections.defaultdict(list)
    skipped = 0
    for sha, subject in commits():
        m = SUBJECT.match(subject)
        if not m:
            skipped += 1
            continue
        heading = TYPES.get(m["type"], m["type"].title())
        scope = f"<b>{html.escape(m['scope'])}</b> — " if m["scope"] else ""
        bang = '<span class="breaking">BREAKING</span> ' if m["bang"] else ""
        groups[heading].append(
            f"    <li>{bang}{scope}{html.escape(m['desc'])} <code>{sha}</code></li>"
        )

    body = ["<h2>All changes</h2>"]
    ordered = list(TYPES.values()) + sorted(set(groups) - set(TYPES.values()))
    for heading in ordered:
        if heading not in groups:
            continue
        body.append(f"  <h3>{html.escape(heading)}</h3>")
        body.append("  <ul>")
        body.extend(groups[heading])
        body.append("  </ul>")
    if skipped:
        body.append(
            f'  <div class="note">{skipped} commit(s) did not follow Conventional '
            "Commits and are not listed.</div>"
        )
    return HEAD + "\n".join(body) + FOOT


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if CHANGELOG.html is out of date",
    )
    args = parser.parse_args(argv)

    generated = render()
    if args.check:
        current = ""
        if os.path.exists(OUTPUT):
            with open(OUTPUT, encoding="utf-8") as f:
                current = f.read()
        if current != generated:
            print("CHANGELOG.html is out of date; run tools/generate_changelog.py")
            return 1
        return 0

    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write(generated)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
